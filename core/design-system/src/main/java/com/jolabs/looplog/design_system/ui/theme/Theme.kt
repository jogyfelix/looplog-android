/**
 * Mirrors Android's system "Increase contrast" accessibility setting
 * ([UiModeManager.getContrast], API 34+). Below API 34 this always reports [Standard], since the
 * platform API to read contrast level doesn't exist yet.
 */
enum class ContrastLevel { Standard, Medium, High }

/**
 * Thresholds are a best-effort midpoint split of [UiModeManager.getContrast]'s documented 0.0
 * (standard) / 0.5 (medium) / 1.0 (high) range - re-verify against current platform docs/CTS if
 * this ever needs to be exact rather than approximate.
 */
private fun contrastLevelFor(contrast: Float): ContrastLevel = when {
    contrast >= 0.75f -> ContrastLevel.High
    contrast >= 0.25f -> ContrastLevel.Medium
    else -> ContrastLevel.Standard
}

@Composable
private fun rememberSystemContrastLevel(context: Context): ContrastLevel {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.UPSIDE_DOWN_CAKE) return ContrastLevel.Standard

    val uiModeManager = remember(context) { context.getSystemService(UiModeManager::class.java) }
    var contrast by remember(uiModeManager) { mutableFloatStateOf(uiModeManager?.contrast ?: 0f) }

    DisposableEffect(uiModeManager) {
        if (uiModeManager == null) return@DisposableEffect onDispose {}
        val listener = UiModeManager.ContrastChangeListener { contrast = it }
        uiModeManager.addContrastChangeListener(context.mainExecutor, listener)
        onDispose { uiModeManager.removeContrastChangeListener(listener) }
    }

    return contrastLevelFor(contrast)
}

private fun staticColorScheme(darkTheme: Boolean, contrastLevel: ContrastLevel): ColorScheme =
    when (contrastLevel) {
        ContrastLevel.High -> if (darkTheme) highContrastDarkColorScheme else highContrastLightColorScheme
        ContrastLevel.Medium -> if (darkTheme) mediumContrastDarkColorScheme else mediumContrastLightColorScheme
        ContrastLevel.Standard -> if (darkTheme) darkScheme else lightScheme
    }

@Composable
fun HabitAppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Dynamic color is available on Android 12+
    dynamicColor: Boolean = true,
    // A non-System accent overrides the primary roles with a fixed preset palette.
    accent: AppAccent = AppAccent.SYSTEM,
    content: @Composable () -> Unit
) {
    val context = LocalContext.current
    val contrastLevel = rememberSystemContrastLevel(context)

    val baseScheme = when {
        // Accessibility wins over theming: if the user has asked for more contrast, honor that
        // even when dynamic (wallpaper-derived) color would otherwise be used, since dynamic
        // color's contrast is out of the app's control. A chosen accent also opts out of the
        // wallpaper-dynamic path so its color is what's actually shown.
        accent == AppAccent.SYSTEM && dynamicColor &&
            Build.VERSION.SDK_INT >= Build.VERSION_CODES.S && contrastLevel == ContrastLevel.Standard -> {
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        else -> staticColorScheme(darkTheme, contrastLevel)
    }

    val colorScheme = applyAccent(baseScheme, accent, darkTheme)

    MaterialTheme(
        colorScheme = colorScheme,
        typography = AppTypography,
        content = content
    )
}

